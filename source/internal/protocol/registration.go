package protocol

import (
	"encoding/json"
	"time"
)

// Result codes returned by the durable registration tools. They travel in the
// result body so the local MCP client can branch on the reason; MCP tool errors
// are reserved for malformed calls and internal failures.
const (
	CodeInvalid          = "invalid"
	CodeNotFound         = "not-found"
	CodeDetached         = "detached"
	CodeSuspended        = "suspended"
	CodeOwned            = "owned"
	CodeRevisionMismatch = "revision-mismatch"
	CodeStaleProbe       = "stale-probe"
	CodeStorage          = "storage"
	CodeCapacity         = "capacity"
	CodeInvalidToken     = "invalid-token"
)

// ReattachAfterCleanupCapability describes the current holder, not its grant history.
const ReattachAfterCleanupCapability = "registration.reattach-after-cleanup"

// RegisterRequest is the explicit registration issued by the local MCP client
// when the model calls attach_session. It creates, revives or renames the
// registration owned by (harness, session UUID, client id).
type RegisterRequest struct {
	Holder           *ReceiverHolder `json:"holder,omitempty"`
	HolderProof      *HolderProof    `json:"holderProof,omitempty"`
	Capabilities     []string        `json:"capabilities,omitempty" jsonschema:"optional delivery capabilities supported by this receiver on this lease"`
	Harness          string          `json:"harness"`
	SessionID        string          `json:"sessionId"`
	PID              int             `json:"pid"`
	CWD              string          `json:"cwd"`
	ClientID         string          `json:"clientId" jsonschema:"Stable per-PC client identity generated by the local MCP client"`
	Name             string          `json:"name,omitempty" jsonschema:"Requested communication name; ignored when an admission grant assigns one"`
	Token            string          `json:"token,omitempty" jsonschema:"Optional admission token for token-protected projects; never used for resume"`
	ChannelID        string          `json:"channelId" jsonschema:"Fresh ingress lease for this receiver"`
	IngressPending   bool            `json:"ingressPending,omitempty" jsonschema:"Registration is connected but its local delivery channel has not been activated"`
	Secret           string          `json:"secret" jsonschema:"Client-generated resume secret; the server stores only its hash"`
	RequestID        string          `json:"requestId" jsonschema:"Idempotency key for retries"`
	ExpectedRevision uint64          `json:"expectedRevision,omitempty" jsonschema:"Registration revision the client last stored; zero for a first registration. A different current revision rejects this stale request"`
	ProcessKey       string          `json:"processKey,omitempty"`
	MAC              string          `json:"mac,omitempty"`
}

// ResumeRequest restores an existing registration after a client or server
// restart. It never creates a registration and is rejected after an explicit detach.
type ResumeRequest struct {
	Holder           *ReceiverHolder `json:"holder,omitempty"`
	HolderProof      *HolderProof    `json:"holderProof,omitempty"`
	Capabilities     []string        `json:"capabilities,omitempty" jsonschema:"optional delivery capabilities supported by this receiver on this lease"`
	RegistrationID   string          `json:"registrationId"`
	Harness          string          `json:"harness"`
	SessionID        string          `json:"sessionId"`
	PID              int             `json:"pid"`
	CWD              string          `json:"cwd"`
	ClientID         string          `json:"clientId"`
	ChannelID        string          `json:"channelId"`
	IngressPending   bool            `json:"ingressPending,omitempty"`
	Secret           string          `json:"secret"`
	RequestID        string          `json:"requestId"`
	ProcessKey       string          `json:"processKey,omitempty"`
	ExpectedRevision uint64          `json:"expectedRevision,omitempty" jsonschema:"Registration revision the client last observed; a newer revision rejects this stale resume"`
}

// RenewRequest is the heartbeat. It carries the lease, never the secret.
// Activity is raw optional JSON so invalid observations cannot fail a valid
// heartbeat in schema validation before authorization and bounded decoding.
type RenewRequest struct {
	Epoch          string          `json:"epoch,omitempty"`
	AckThrough     uint64          `json:"ackThrough,omitempty"`
	RuntimeInfo    json.RawMessage `json:"runtimeInfo,omitempty"`
	Activity       json.RawMessage `json:"activity,omitempty"`
	RegistrationID string          `json:"registrationId"`
	ChannelID      string          `json:"channelId"`
	IngressPending bool            `json:"ingressPending,omitempty"`
}

// ProbeAnswer reports the client's local identity re-verification for a probe.
type ProbeAnswer struct {
	RegistrationID string `json:"registrationId"`
	ProbeID        string `json:"probeId"`
	Revision       uint64 `json:"revision"`
	ChannelID      string `json:"channelId"`
	OK             bool   `json:"ok"`
	PID            int    `json:"pid,omitempty"`
	CWD            string `json:"cwd,omitempty"`
	ProcessKey     string `json:"processKey,omitempty"`
}

// PendingProbe is handed to the owning client on resume or renewal.
type PendingProbe struct {
	ID       string    `json:"id"`
	Revision uint64    `json:"revision"`
	Deadline time.Time `json:"deadline"`
}

const CredentialScopesCapability = "credential-scopes-v1"

type RegisterResult struct {
	ServerVersion      string           `json:"serverVersion,omitempty"`
	MessageAckVersion  int              `json:"messageAckVersion,omitempty"`
	CredentialScopes   []string         `json:"credentialScopes,omitempty"`
	HolderChallenge    *HolderChallenge `json:"holderChallenge,omitempty"`
	RuntimeInfoVersion int              `json:"runtimeInfoVersion,omitempty"`
	ActivityVersion    int              `json:"activityVersion,omitempty"`
	Code               string           `json:"code,omitempty"`
	Session            Session          `json:"session"`
	Warning            string           `json:"warning,omitempty"`
	PendingProbe       *PendingProbe    `json:"pendingProbe,omitempty"`
}

type ProbeResult struct {
	Code    string  `json:"code,omitempty"`
	Removed bool    `json:"removed,omitempty"`
	Session Session `json:"session"`
}

// Selectors address a single remote registration namespace.
const (
	SelectorRegistration = "registration:"
	SelectorName         = "name:"
	SelectorSession      = "session:"
)
